export function mergeLegacyArticles(cmsArticles: Article[]) {
  const publishedSlugs = new Set(cmsArticles.filter((article) => article.status === "published").map((article) => article.slug));
  return [...cmsArticles, ...LEGACY_ARTICLES.filter((article) => !publishedSlugs.has(article.slug))].sort(
    (left, right) => Date.parse(right.updatedAt) - Date.parse(left.updatedAt),
  );
}
